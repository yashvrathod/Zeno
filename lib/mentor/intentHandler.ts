/**
 * Determines if a response should be eligible for caching.
 * This combines intent classification with stage enforcement results.
 */
export function shouldCacheResponse(
  intent: IntentClassification,
  enforcementAction: EnforcementAction,
  stage: TeachingStage
): { shouldCache: boolean; reason: string } {
  // Don't cache if enforcement action blocks or redirects
  if (enforcementAction.type !== "ALLOW") {
    return {
      shouldCache: false,
      reason: `Enforcement action (${enforcementAction.type}) indicates non-standard handling`
    };
  }

  // Use intent classification's cacheability rules
  if (!intent.shouldEnforceStage) {
    return {
      shouldCache: false,
      reason: "Intent does not require stage enforcement"
    };
  }

  // Don't cache solution requests ever
  if (intent.intent === "solution_request") {
    return {
      shouldCache: false,
      reason: "Solution requests should never be cached"
    };
  }

  // Check intent-specific cacheability
  const cacheableIntents: IntentType[] = [
    "understanding",
    "hint_request",
    "clarification",
    "pattern_recognition",
    "transfer_learning",
    "optimization",
    "approach_validation",
    "edge_case_help"
  ];

  if (!cacheableIntents.includes(intent.intent)) {
    return {
      shouldCache: false,
      reason: `Intent type "${intent.intent}" is not cacheable`
    };
  }

  // Early stages have stricter caching (only truly generic advice)
  if (stage === "EXPLORE" && intent.intent !== "understanding" && intent.intent !== "clarification") {
    return {
      shouldCache: false,
      reason: "EXPLORE stage responses are too context-specific to cache"
    };
  }

  return {
    shouldCache: true,
    reason: "Response meets all cache eligibility criteria"
  };
}

